def on_init(t:int) -> int:
    """Pandas module initialization

    Arguments
    ---------
    - `t`: initialization timestamp

    Returns
    -------
    - `int`: `gldcore.INIT_FAILED` on failure, `gldcore.INIT_OK` on success,
      `gldcore.INIT_DEFER` on defer initialization
    """
    global recorder
    recorder = {}

    global player
    player = {}

    global collector
    collector = {}

    return gldcore.INIT_OK

def on_term(t:int):
    """Terminate all players

    Arguments
    ---------
    - `t`: termination timestamp
    """
    for this in recorder.values():
        this.file.close()

    for this in collector.values():
        this.file.close()

    return None

