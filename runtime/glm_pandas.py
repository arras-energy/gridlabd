"""GridLAB-D Pandas Module

The `pandas` module load the `player` and `recorder` runtime classes and the
supporting Python module `glm_pandas.py`, which are used to read and write
CSV files. To load the `pandas` runtime classes, add the following line to
your GLM file.

    #include "pandas.glm"

Players
-------

Players are used to read CSV files into memory and synchronize the columns to
properties of the player's parent object. By default the first column is the
timestamps of the data rows to synchronize.

The following properties are supported by players.

- `property`: a comma-delimited list of property names to read from the CSV
  file. If `property` is omitted, the CSV file must contain a header line to
  indicate which properties are to be read in. 

- `file`: the pathname of the CSV file to read.

- `timezone`: the timezone of the timestamps if not specified in the
  data file's `timestamp` column.

- `options`: JSON text of options overrides for `pandas.read_csv()`. The
  default `options` depends on whether `property` is specified.

| Options | `property` set | no `property` |
| ------- | -------------- | ------------- |
| `header` | `None` | `0` |
| `parse_dates` | `["timestamp"]` | `True` |
| `usecols` | `"timestamp"]+properties` | `None` |
| `names` | `["timestamp"]+properties` | `None` |
| `converters` | `{x:str for x in properties}` | `None` |
| `dtype` | `None` | `str `|

The following examples illustrate how to use players. The GLM class `example`
is defined as follows.

    class test
    {
        double x[s];
        double y[m];
    }

where the terms in square brackets after the property names are their
units, i.e., seconds and meters, respectively. If values are provided
with different units, then the data will be automatically converted to
units specified by the class.

*Simple player*:

In this example, the file `test_player.csv` contains this data.

    timestamp,x,y
    2000-01-01 00:00:00,60,0
    2000-01-01 01:00:00,61,1
    2000-01-01 02:00:00,62,2
    2000-01-01 04:00:00,64,3
    2000-01-01 05:00:00,65,4
    2000-01-01 10:00:00,64,5
    2000-01-01 11:00:00,63,6
    2000-01-01 12:00:00,62,7
    2000-01-01 13:00:00,61,8
    2000-01-01 14:00:00,60,9


Use the following to update the properties `x` and `y` in an object of class
`test` from data in the file `test_player.csv`.

    object example
    {
        object player
        {
            file "test_player.csv";
        };
    }

*Player missing timezones*:

If you need to specify the timezone for the timestamp use the following.

    object example
    {
        object player
        {
            file "test_player.csv";
            timezone "America/Los_Angeles";
        };
    }

Note that only timezones supported by Python `zoneinfo` module are supported.

*Player missing header row*:

The next example illustrates how to read data from the same CSV file when it
has no header to provide the property names.

    object example
    {
        object player
        {
            file "test_player.csv";
            options "{'header':None,'names':['timestamp','x','y']}";
            property "x,y";
        };
    }

Recorders
---------

Recorders are used to write CSV files from memory when objects are synchronize
from properties of the recorder's parent object. By default the first column
is the timestamp of the data rows generated by synchronization events.

The following properties are supported by recorders.

- `property`: a comma-delimited list of property names to write to the
  CSV file.

- `file`: the name of the CSV file to write. Any file format supported
  by `pandas.read_csv()` is supported, include compressed CSV files, e.g.,
  using `gzip`.

- `interval[s]`: the interval at which to sample the properties. If
  `0` (the default) is specified, then the properties are sampled at every
  iteration. If `-1` is specified, then the properties are sampled only when
  one of the values changes.

- `timezone`: the timezone of the timestamps to write the data file.
  The default timezone is UTC.

- `dtformat`: the date/time format to use when writing timestamps.

- `units`: specifies whether and how units information is include. The
  default is `None`, which does not include any units information in the
  output. If `INLINE` is specified, the units are included with the value
  is each cell. If `HEADER` is specified, the units are included as part
  of the column names, e.g., `name[unit]`.

- `flush`: specifies whether the output buffer is flushed with each write.


The following examples illustrate how to use a recorder for the same GLM class
used in the player examples.

*Simple recorder*:

This example records the properties to columns of the CSV file.

    object recorder
    {
        file "test_recorder.csv";
        property "x,y";
    }

*Recorder timezone*:

To specify the timezone of the `timestamp` column include the `timezone`
property.

    object recorder
    {
        file "test_recorder.csv";
        property "x,y";
        timezone "America/Los_Angeles";
    };

*Recorders timestamp format*:

To specify the date/time format fof the timestaom include the `dtformat`
property.

    object recorder
    {
        file "test_recorder.csv";
        property "x,y";
        timezone "America/Los_Angeles";
        dtformat "%Y-%m-%d %H:%M:%S %Z";
    };
"""

