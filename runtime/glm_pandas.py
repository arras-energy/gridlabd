def player_init(obj:str,t:int) -> int:
    """Initialize a player

    Arguments
    ---------
    - `obj`: object name
    - `t`: initial timestamp

    Returns
    -------
    - `int`: 0 on success, non-zero on failure
    """

    # get player info
    parent = gldcore.get_value(obj,"parent")

    properties = [x.strip() for x in gldcore.get_value(obj,"property").split(",") if x != ""]

    options = eval(gldcore.get_value(obj,"options"))
    options = options if options else {}

    def set_defaults(data,**kwargs):
        for key,value in kwargs.items():
            if not key in data:
                data[key] = value
        return data

    set_defaults(options,
        header="infer" if properties else 0,
        parse_dates=["timestamp"] if properties else True,
        usecols=["timestamp"]+properties if properties else None,
        converters={x:str for x in properties} if properties else None,
        dtype=None if properties else str,
        )

    file = gldcore.get_value(obj,"file")
    data = pd.read_csv(file,**options)

    if not properties:
        properties = data.columns[1:].tolist()
    assert properties, f"{obj=} no properties specified"

    source = {}
    unit = {}
    for prop in properties:
        name,unit[prop] = name_unit(prop)
        fromobj,name = name.split(":",1) if ":" in prop else (parent,name)
        assert name, f"no target property specified"
        try:
            source[prop] = gldcore.property(parent,name)
        except Exception as err:
            e_type, e_value, _ = sys.exc_info()
            raise e_type(f"{obj}.properties: '{parent}.{name}' {e_value}") from err

    try:
        timezone = gldcore.get_value(obj,"timezone")
        data.timestamp = pd.DatetimeIndex(data.timestamp).tz_localize(timezone if timezone else "UTC")
    except:
        data.timestamp = pd.DatetimeIndex(data.timestamp).tz_convert("UTC")

    # setup player
    this = {
        "data": data,
        "row": 0,
        "source": source,
        "unit": unit,
        "timestamp": None
        }
    player[obj] = MutableData(**this)

    return gldcore.INIT_OK

def player_precommit(obj:str,t:int) -> int:
    """Update a player

    Arguments
    ---------

    - `obj`: object name
    - `t`: current timestamp

    Returns
    -------

    - `int`: next timestamp
    """
    this = player[obj]
    try:
        data = this.data.loc[this.row]
    except KeyError:
        return gldcore.NEVER

    this.timestamp = TIMESTAMP(int(data.timestamp.timestamp()))

    # update time was missed
    if this.timestamp < t:
        gldcore.warning(f"missed timestamp {this.timestamp}>")

    # update time is in the future
    if this.timestamp > t:
        return this.timestamp

    # update time has arrived
    for src,prop in this.source.items():
        if this.unit[src] is None:
            value = str(data[src])
        else:
            value = f"{data[src]} {this.unit[src]}"
        prop.set_value(value)

    # move to next row
    this.row += 1
    try:
        tnext = int(this.data.loc[this.row,"timestamp"].timestamp())
        return -tnext
    except KeyError:
        return gldcore.NEVER

